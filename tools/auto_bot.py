#!/usr/bin/env python3
"""Auto-detect and launch v4/v5/RLGym bots through EvilRLBot."""
from __future__ import annotations

import configparser
import json
import os
import hashlib
import shlex
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))

from common.detection import detect_bot
from v4cfg_to_v5 import build as build_v4_match, q

V5_PY = ROOT / ".venv" / "bin" / "python"
V5_BRIDGE = ROOT / "src" / "v5_bridge.py"
RUNNER = ROOT / "run.py"


def _looks_template() -> str:
    return (ROOT / "legacy_bot" / "looks.cfg").read_text()


def _read_v4_name(cfg: Path) -> str:
    cp = configparser.RawConfigParser()
    cp.read(cfg, encoding="utf-8")
    return cp.get("Locations", "name", fallback=cfg.stem)


def _is_v5_match(path: Path) -> bool:
    try:
        text = path.read_text(errors="ignore").lower()
    except OSError:
        return False
    return "[rlbot]" in text and "[[cars]]" in text


def _is_v5_agent(path: Path) -> bool:
    try:
        text = path.read_text(errors="ignore").lower()
    except OSError:
        return False
    return "[settings]" in text and ("run_command" in text or "agent_id" in text)


def _is_v4_match(path: Path) -> bool:
    try:
        text = path.read_text(errors="ignore").lower()
    except OSError:
        return False
    return "[match configuration]" in text and "[participant configuration]" in text


def _is_v4_bot(path: Path) -> bool:
    try:
        text = path.read_text(errors="ignore").lower()
    except OSError:
        return False
    return "[locations]" in text and "python_file" in text


def _find(root: Path, predicate) -> Path | None:
    if root.is_file() and predicate(root):
        return root
    if not root.is_dir():
        return None
    candidates = sorted(
        [p for p in root.glob("*") if p.is_file()],
        key=lambda p: (p.name not in {"rlbot.cfg", "bot.cfg", "bot.toml"}, p.name.lower()),
    )
    for p in candidates:
        if predicate(p):
            return p
    return None


def _default_match_lines(agent_config: str, bot_team: int = 1, game_map: str = "Stadium_P", game_mode: str = "Soccar") -> list[str]:
    human_team = 1 - bot_team
    return [
        "# Generated by EvilRLBot smart importer",
        "[rlbot]",
        'launcher = "Steam"',
        "auto_start_agents = true",
        "wait_for_agents = true",
        "",
        "[match]",
        f'game_mode = {q(game_mode)}',
        f'game_map_upk = {q(game_map)}',
        "skip_replays = true",
        "instant_start = false",
        'existing_match_behavior = "Restart"',
        "enable_rendering = true",
        "enable_state_setting = true",
        "freeplay = false",
        "",
        "[mutators]",
        'match_length = "FiveMinutes"',
        'max_score = "Unlimited"',
        'overtime = "Unlimited"',
        'series_length = "Unlimited"',
        'game_speed = "Default"',
        'ball_max_speed = "Default"',
        'ball_type = "Default"',
        'ball_weight = "Default"',
        'ball_size = "Default"',
        'ball_bounciness = "Default"',
        'boost_amount = "NormalBoost"',
        'rumble = "Off"',
        'boost_strength = "One"',
        'gravity = "Default"',
        'demolish = "Default"',
        'respawn_time = "ThreeSeconds"',
        "",
        "[[cars]]",
        'type = "Human"',
        f"team = {human_team}",
        "",
        "[[cars]]",
        f"config_file = {q(agent_config)}",
        f"team = {bot_team}",
        "auto_start = true",
    ]


def _generate_v4_agent(cfg: Path, out: Path, report: dict, deps_source: Path | None = None) -> Path:
    player = out / "player"
    player.mkdir(parents=True, exist_ok=True)
    name = _read_v4_name(cfg)
    run_sh = player / "run.sh"
    run_sh.write_text(
        "#!/usr/bin/env bash\n"
        "set -euo pipefail\n"
        f"export EVILRLBOT_V4_CONFIG={shlex.quote(str(cfg.resolve()))}\n"
        f"export EVILRLBOT_V4_SOURCE={shlex.quote(str((deps_source or cfg).resolve()))}\n"
        f"export EVILRLBOT_V4_DEPS={shlex.quote(str(Path.home() / '.local/share/evilrlbot/dependencies' / hashlib.sha256(str((deps_source or cfg).resolve()).encode()).hexdigest()[:18]))}\n"
        f"export EVILRLBOT_DETECTED_OBS={shlex.quote(str(report.get('observation', 'unknown')))}\n"
        f"export EVILRLBOT_DETECTED_TICK_SKIP={shlex.quote(str(report.get('tick_skip') or ''))}\n"
        f"exec {shlex.quote(str(V5_PY))} {shlex.quote(str(V5_BRIDGE))}\n"
    )
    run_sh.chmod(0o755)
    agent = player / "agent.toml"
    agent.write_text(
        "#:schema https://rlbot.org/schemas/agent.json\n"
        "[settings]\n"
        f"name = {q(name)}\n"
        'root_dir = ""\n'
        'run_command = "./run.sh"\n'
        'run_command_linux = "./run.sh"\n'
        f'agent_id = "evilrlbot/auto-v4-{hashlib.sha256(str(out.resolve()).encode()).hexdigest()[:12]}"\n'
        'logo_file = ""\n\n'
        "[details]\n"
        f"description = {q('Auto-detected RLBot v4 bot via EvilRLBot hybrid frontend')}\n"
        f"fun_fact = {q('obs=' + str(report.get('observation')) + ', engine=v5')}\n"
        'developer = "EvilRLBot smart importer"\n'
        'language = "Python"\n'
        'tags = []\n'
    )
    return agent


def _generate_v4_cfg_from_python(py: Path, out: Path) -> Path:
    cfg_dir = out / "legacy"
    cfg_dir.mkdir(parents=True, exist_ok=True)
    looks = cfg_dir / "looks.cfg"
    looks.write_text(_looks_template())
    cfg = cfg_dir / "bot.cfg"
    cfg.write_text(
        "[Locations]\n"
        f"python_file = {py.resolve()}\n"
        f"name = {py.stem}\n"
        f"looks_config = {looks.resolve()}\n"
        "supports_early_start = False\n"
        "supports_standalone = False\n"
        "maximum_tick_rate_preference = 120\n"
        "requires_tkinter = False\n"
        "use_virtual_environment = False\n"
        "requires_py37 = False\n\n"
        "[Details]\n"
        "developer = imported\n"
        "description = Smart-imported by EvilRLBot\n"
        "language = Python\n"
        "tags = 1v1\n\n"
        "[Bot Parameters]\n"
    )
    return cfg


def _generate_v5_agent_from_python(py: Path, out: Path, report: dict) -> Path:
    player = out / "player"
    player.mkdir(parents=True, exist_ok=True)
    local_python = None
    for candidate in (py.parent / ".venv/bin/python", py.parent / "venv/bin/python"):
        if candidate.is_file():
            local_python = candidate
            break
    executable = local_python or V5_PY
    agent = player / "agent.toml"
    agent.write_text(
        "#:schema https://rlbot.org/schemas/agent.json\n"
        "[settings]\n"
        f"name = {q(py.stem)}\n"
        f"root_dir = {q(str(py.parent.resolve()))}\n"
        f"run_command = {q(str(executable) + ' ' + str(py.resolve()))}\n"
        f"run_command_linux = {q(str(executable) + ' ' + str(py.resolve()))}\n"
        f'agent_id = "evilrlbot/auto-v5-{hashlib.sha256(str(out.resolve()).encode()).hexdigest()[:12]}"\n'
        'logo_file = ""\n\n'
        "[details]\n"
        f"description = {q('Auto-detected native RLBot v5 bot')}\n"
        f"fun_fact = {q('obs=' + str(report.get('observation')))}\n"
        'developer = "EvilRLBot smart importer"\n'
        'language = "Python"\n'
        'tags = []\n'
    )
    return agent


def resolve(path: Path, report: dict, out: Path, bot_team: int = 1, game_map: str = "Stadium_P", game_mode: str = "Soccar") -> Path:
    v4_match = _find(path, _is_v4_match)
    if v4_match is not None:
        return build_v4_match(v4_match)

    v5_match = _find(path, _is_v5_match)
    if v5_match is not None:
        return v5_match.resolve()

    v5_agent = _find(path, _is_v5_agent)
    if v5_agent is not None and report.get("framework") in {"rlbot-v5", "hybrid-v4-v5"}:
        match = out / "match.toml"
        match.write_text("\n".join(_default_match_lines(str(v5_agent.resolve()), bot_team, game_map, game_mode)) + "\n")
        return match

    v4_bot = _find(path, _is_v4_bot)
    if v4_bot is not None:
        agent = _generate_v4_agent(v4_bot, out, report)
        match = out / "match.toml"
        match.write_text("\n".join(_default_match_lines(str(agent.resolve()), bot_team, game_map, game_mode)) + "\n")
        return match

    entrypoints = [Path(x) for x in report.get("entrypoints") or []]
    if path.is_file() and path.suffix.lower() == ".py":
        entrypoints.insert(0, path)
    py = next((x for x in entrypoints if x.is_file()), None)
    if py is None:
        raise RuntimeError("No usable RLBot config or Python entrypoint found")

    if report.get("framework") == "rlbot-v5":
        agent = _generate_v5_agent_from_python(py, out, report)
    else:
        cfg = _generate_v4_cfg_from_python(py, out)
        agent = _generate_v4_agent(cfg, out, report, deps_source=path)
    match = out / "match.toml"
    match.write_text("\n".join(_default_match_lines(str(agent.resolve()), bot_team, game_map, game_mode)) + "\n")
    return match


def main():
    if len(sys.argv) < 2:
        raise SystemExit("usage: evil-rlbot-auto <bot-file-or-directory> [--generate-only] [--team=0|1] [--map=UPK] [--mode=Soccar]")
    target = Path(sys.argv[1]).expanduser().resolve()
    bot_team = 1
    game_map = "Stadium_P"
    game_mode = "Soccar"
    for arg in sys.argv[2:]:
        if arg.startswith("--team="):
            bot_team = int(arg.split("=", 1)[1])
        elif arg.startswith("--map="):
            game_map = arg.split("=", 1)[1]
        elif arg.startswith("--mode="):
            game_mode = arg.split("=", 1)[1]
    if bot_team not in (0, 1):
        raise SystemExit("--team must be 0 or 1")
    if not target.exists():
        raise SystemExit(f"not found: {target}")

    report = detect_bot(target)
    out = ROOT / ".generated" / "auto"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    (out / "diagnostics.json").write_text(json.dumps(report, indent=2))
    print(
        "Detected:",
        f"framework={report.get('framework')}",
        f"obs={report.get('observation')}",
        f"action={report.get('action_parser')}",
        f"tick_skip={report.get('tick_skip')}",
        f"model={report.get('model_runtime')}",
    )
    match = resolve(target, report, out, bot_team, game_map, game_mode)
    print(f"Generated/selected v5 match: {match}")

    if "--generate-only" not in sys.argv[2:]:
        os.execv(str(V5_PY), [str(V5_PY), str(RUNNER), str(match)])


if __name__ == "__main__":
    main()
